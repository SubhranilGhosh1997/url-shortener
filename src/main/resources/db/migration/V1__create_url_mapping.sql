-- Short links. Matches the UrlMapping entity; Hibernate only validates it (ddl-auto: validate).
CREATE TABLE url_mapping (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Set in a second save, right after the id is generated, so it is briefly NULL.
    short_code   VARCHAR(255),
    original_url VARCHAR(2048) NOT NULL,
    created_at   TIMESTAMP(6)  NOT NULL,
    CONSTRAINT uk_url_mapping_short_code UNIQUE (short_code)
);

-- "Was this URL shortened before?" lookup in UrlService.shortenUrl.
-- Not unique: two simultaneous requests for a new URL may both insert it.
CREATE INDEX idx_url_mapping_original_url ON url_mapping (original_url);
