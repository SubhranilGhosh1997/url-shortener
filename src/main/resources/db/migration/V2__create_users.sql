-- User accounts (auth module). Kept free of references to other tables so the auth module
-- can later move to its own service and database.
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Stored lowercased and trimmed; 320 is the maximum length of an email address.
    email         VARCHAR(320) NOT NULL,
    -- BCrypt hash (60 chars); room for a stronger algorithm later.
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);
